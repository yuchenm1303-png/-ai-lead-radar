create table if not exists public.lead_radar_retrieval_settings (
  id smallint primary key default 1 check (id = 1),
  auto_enabled boolean not null default false,
  auto_interval_minutes integer not null default 60 check (auto_interval_minutes between 15 and 1440),
  auto_queries_per_scan integer not null default 1 check (auto_queries_per_scan between 1 and 3),
  auto_provider_calls_per_scan integer not null default 1 check (auto_provider_calls_per_scan between 1 and 6),
  manual_queries_per_scan integer not null default 2 check (manual_queries_per_scan between 1 and 3),
  manual_provider_calls_per_scan integer not null default 3 check (manual_provider_calls_per_scan between 1 and 6),
  provider_calls_per_hour_cap integer not null default 6 check (provider_calls_per_hour_cap between 1 and 30),
  updated_at timestamptz not null default now()
);

insert into public.lead_radar_retrieval_settings (id)
values (1)
on conflict (id) do nothing;

alter table public.lead_radar_retrieval_settings enable row level security;

